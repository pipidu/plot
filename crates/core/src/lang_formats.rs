//! 带参数的状态栏句子。键是简体中文格式串，孔的顺序必须和中文一致。
//! `trf!` 先按中文填好参数，再把孔里的文字嵌进这里的句子，不再回落到英文。

use crate::Language;

pub fn template(language: Language, zh: &str) -> Option<&'static str> {
    let table: &[(&str, &str)] = match language {
        Language::ZhHant => ZH_HANT,
        Language::De => DE,
        Language::Fr => FR,
        Language::Ru => RU,
        Language::Es => ES,
        Language::Cs => CS,
        Language::PtBr => PT_BR,
        Language::Zh | Language::En => return None,
    };
    table.iter().find(|(key, _)| *key == zh).map(|(_, text)| *text)
}

